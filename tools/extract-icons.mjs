// Usage: node tools/extract-icons.mjs <path-to-node_modules>
// Lucide is ISC-licensed (https://lucide.dev/license).
import fs from "node:fs";
import path from "node:path";

const NAMES = [
  "layout-dashboard", "ticket", "users", "settings", "circle-plus", "life-buoy", "menu",
  "search", "x", "shield-check", "log-out", "log-in", "chevron-down", "chevron-up",
  "chevron-right", "bell", "bell-ring", "bell-off", "check-check", "check", "list",
  "layout-grid", "inbox", "message-square", "message-square-plus", "clock", "bookmark",
  "bookmark-plus", "loader-circle", "arrow-left", "arrow-right", "lock", "user-plus",
  "plus", "hash", "send", "paperclip", "file-text", "download", "image", "image-plus",
  "circle-check", "phone", "house", "list-tree", "at-sign", "monitor", "tablet", "laptop", "user-round", "eye-off", "sparkles", "lock-keyhole", "mail-check", "history", "folder", "user-minus", "circle-dot", "list-checks", "smartphone", "trash-2", "flag", "pencil", "zap", "mail", "building-2",
  "triangle-alert", "moon", "sun", "bold", "italic", "underline", "strikethrough",
  "baseline", "highlighter", "code", "code-xml", "list-ordered", "list-todo", "quote",
  "minus", "link", "table", "rows-3", "columns-3", "align-left", "align-center",
  "align-right", "undo-2", "redo-2", "chevron-left", "chevrons-left", "chevrons-right",
  "book-open", "git-merge", "arrow-up-down", "chart-column", "eye", "wand-sparkles", "unlink", "timer", "link-2", "pen-line", "external-link", "thumbs-up",
  "type", "smile", "frown", "scroll-text", "globe", "route", "webhook", "plug", "calendar-clock", "building", "star", "activity", "message-circle",
  "layers", "copy", "crown", "user-round-check", "user-x", "key-round", "shield", "shield-alert", "sliders-horizontal", "circle-user-round", "info", "rotate-ccw", "users-round", "ellipsis",
];

const nm = process.argv[2] ?? "node_modules";
const dir = path.join(nm, "lucide-react", "dist", "esm", "icons");
const out = {};
for (const name of NAMES) {
  let src = fs.readFileSync(path.join(dir, `${name}.mjs`), "utf8");
  const alias = /export \{ default \} from ['"]\.\/([\w-]+)\.mjs['"]/.exec(src);
  if (alias) src = fs.readFileSync(path.join(dir, `${alias[1]}.mjs`), "utf8");
  const m = /const __iconData = (\{[\s\S]*?\n\});/.exec(src);
  if (!m) throw new Error(`Cannot parse ${name}`);
  const data = Function(`return (${m[1]})`)();
  out[name] = data.node
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .filter(([k]) => k !== "key")
        .map(([k, v]) => `${k}="${String(v).replace(/"/g, "&quot;")}"`)
        .join(" ");
      return `<${tag} ${a}/>`;
    })
    .join("");
}

let php = "<?php\n// Generated by tools/extract-icons.mjs — Lucide icons (ISC license, https://lucide.dev).\nreturn [\n";
for (const [k, v] of Object.entries(out)) {
  php += `  '${k}' => '${v.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}',\n`;
}
php += "];\n";
fs.writeFileSync(path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "..", "src", "lib", "icons_data.php"), php);
console.log(`Wrote ${Object.keys(out).length} icons`);
